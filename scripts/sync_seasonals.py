_DROP_IMPORTS = ("import anthropic\n", "from ai_chat import run_chat\n", "from hl_model import render_hl_tab\n")
_REL = [("import settlement_bank\n", "from . import settlement_bank\n"),
        ("import stocks_use\n", "from . import stocks_use\n"),
        ("import trend_board\n", "from . import trend_board\n"),
        ("from legacy_history import", "from .legacy_history import"),
        ("from massive_api import", "from .massive_api import"),
        ("from report_dates import", "from .report_dates import"),
        ("from table_png import", "from .table_png import")]


def transform_app(src: str) -> str:
    s = src.replace("\r\n", "\n")
    for line in _DROP_IMPORTS:
        if s.count(line) != 1:
            raise SystemExit(f"source changed: expected exactly one {line.strip()!r}")
        s = s.replace(line, "")
    for old, new in _REL:
        if s.count(old) != 1:
            raise SystemExit(f"source changed: expected exactly one {old.strip()!r}")
        s = s.replace(old, new)
    a, b = s.find("st.set_page_config("), s.find("COMMODITIES = [")
    if not (0 < a < b):
        raise SystemExit("source changed: can't find the page-config block before COMMODITIES")
    s = s[:a] + s[b:]
    m = s.find("\ndef main():")
    if m < 0:
        raise SystemExit("source changed: no main()")
    s = s[:m].rstrip("\n") + "\n" + RENDER
    for needed in ("def refresh_prices", "def render_trends", "def render_commodity", "def load_wasde_dates",
                   "def render_cross_commodity_spread", "def render_report_calendar", "def _selected_report_dates"):
        if needed not in s:
            raise SystemExit(f"source changed: {needed!r} is gone")
    return HEADER + s


def build() -> dict[str, bytes]:
    """The whole generated package as {relative path: bytes}."""
    if not (SRC / "app.py").exists():
        raise SystemExit(f"source app not found at {SRC}")
    files = {"dashboard.py": transform_app((SRC / "app.py").read_text(encoding="utf-8")).encode("utf-8"),
             "__init__.py": b'"""Generated copy of the Grain Futures Seasonals dashboard; see scripts/sync_seasonals.py."""\n'}
    for name in VERBATIM:
        raw = (SRC / name).read_bytes()
        files[name] = raw if name.endswith(".csv") else HEADER.encode() + raw.replace(b"\r\n", b"\n")
    for name in ASSETS:
        files[f"assets/{name}"] = (SRC / "assets" / name).read_bytes()
    return files


def current() -> dict[str, bytes]:
    return {str(p.relative_to(OUT)).replace("\\", "/"): p.read_bytes()
            for p in OUT.rglob("*") if p.is_file() and "__pycache__" not in p.parts} if OUT.exists() else {}


def diff() -> list[str]:
    want, have = build(), current()
    out = [f"missing: {n}" for n in sorted(want.keys() - have.keys())]
    out += [f"extra: {n}" for n in sorted(have.keys() - want.keys())]
    out += [f"differs: {n}" for n in sorted(want.keys() & have.keys()) if want[n].replace(b"\r\n", b"\n") != have[n].replace(b"\r\n", b"\n")]
    return out


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "status"
    if cmd == "apply":
        want = build()
        for p in list(OUT.rglob("*")) if OUT.exists() else []:
            if p.is_file() and "__pycache__" not in p.parts and str(p.relative_to(OUT)).replace("\\", "/") not in want:
                p.unlink()
        for name, raw in want.items():
            dest = OUT / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(raw)
        print(f"wrote {len(want)} files to {OUT}")
        return 0
    d = diff()
    if cmd in ("status", "check"):
        print("seasonals/ is current" if not d else ("seasonals/ is out of date:\n  " + "\n  ".join(d)
                                                    if cmd == "check" else f"seasonals/ is out of date ({len(d)} files)"))
        return 1 if d else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
