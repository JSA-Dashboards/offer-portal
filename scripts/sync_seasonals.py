"""Keeps seasonals/ (the "Grain Futures Seasonals" page) a generated copy of the grain-seasonal-dashboard app.

    python scripts/sync_seasonals.py status   # is the copy current? (exit 1 if not)
    python scripts/sync_seasonals.py apply    # regenerate seasonals/ from the source app
    python scripts/sync_seasonals.py check    # like status, but prints what differs

The source is ../grain-seasonal-dashboard (override with SEASONALS_SOURCE). Nothing in seasonals/ is edited by hand:
change the source app (or the transform below) and re-run apply. The transform is exact-match on purpose: if the source
moves a line the transform depends on, apply fails loudly instead of producing a half-working copy.

What the copy leaves out: the Ask AI tab (needs an Anthropic key and costs per question) and the H/L Forecast tab
(needs its own workbook). What it changes: no page config / header-hiding CSS (the portal owns the page), no logo/title
(the portal has its header), relative imports, and `render()` in place of `main()`.
"""
