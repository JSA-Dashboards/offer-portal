-- Recreate the throwaway TEST copy of the live schema, with the permissions the app's role needs to use it.
-- Run in a Snowsight SQL WORKSHEET as ACCOUNTADMIN (paste all, "Run all"). Safe to re-run: it replaces the copy.
-- Do this whenever the live schema changes (new columns/tables), so the integration test sees the same shape.
-- Drop the copy when you are done testing, as its own statement:  DROP SCHEMA IF EXISTS OFFER_PORTAL.OFFER_PORTAL_TEST;
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE OFFER_PORTAL;
USE DATABASE OFFER_PORTAL;

CREATE OR REPLACE SCHEMA OFFER_PORTAL.OFFER_PORTAL_TEST CLONE OFFER_PORTAL.OFFER_PORTAL;
GRANT USAGE ON SCHEMA OFFER_PORTAL.OFFER_PORTAL_TEST TO ROLE OFFER_PORTAL_ROLE;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA OFFER_PORTAL.OFFER_PORTAL_TEST TO ROLE OFFER_PORTAL_ROLE;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA OFFER_PORTAL.OFFER_PORTAL_TEST TO ROLE OFFER_PORTAL_ROLE;
GRANT DELETE ON TABLE OFFER_PORTAL.OFFER_PORTAL_TEST.bids TO ROLE OFFER_PORTAL_ROLE;
GRANT DELETE ON TABLE OFFER_PORTAL.OFFER_PORTAL_TEST.bid_suggestions TO ROLE OFFER_PORTAL_ROLE;

-- Checks. Expect: the test schema exists, 18 tables (the live schema's), and the role has USAGE on it.
SELECT COUNT(*) AS test_schema_tables FROM OFFER_PORTAL.INFORMATION_SCHEMA.TABLES WHERE table_schema = 'OFFER_PORTAL_TEST';
SHOW GRANTS ON SCHEMA OFFER_PORTAL.OFFER_PORTAL_TEST;
